    private void generateSelfSigned() {
        output.append("== Generar certificado auto‑firmado (.pfx) ==\n");
        String cn = tfCN.getText().trim();
        String pfxOut = tfPfxOutput.getText().trim();
        String password = new String(pfPfxPass.getPassword());

        // Comando PowerShell: crear CodeSigning cert y exportar PFX
        // Nota: requiere PowerShell y permisos suficientes
        String psCmd =
            "$subject = 'CN=" + cn.replace("'", "''") + "'; " +
            "$cert = New-SelfSignedCertificate -Type CodeSigningCert -Subject $subject -CertStoreLocation Cert:\\CurrentUser\\My; " +
            "$pwd = ConvertTo-SecureString '" + password.replace("'", "''") + "' -AsPlainText -Force; " +
            "Export-PfxCertificate -Cert $cert -FilePath '" + pfxOut.replace("'", "''") + "' -Password $pwd; " +
            "Write-Output $cert.Thumbprint";

        try {
            CommandRunner.run(List.of("powershell.exe", "-NoProfile", "-ExecutionPolicy", "Bypass", "-Command", psCmd), output);
            tfPfxPath.setText(pfxOut); // actualizar campo PFX a la nueva ruta
        } catch (Exception ex) {
            output.append("Error generando auto‑firmado: " + ex.getMessage() + "\n");
        }
    }

