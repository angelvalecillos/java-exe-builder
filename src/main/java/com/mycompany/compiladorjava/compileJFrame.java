// Diálogo para guardar .properties
    private void saveConfigDialog() {
    javax.swing.JFileChooser chooser = new javax.swing.JFileChooser();
    chooser.setDialogTitle("Guardar configuración");
    chooser.setSelectedFile(new java.io.File("compilador-config.properties"));
    int res = chooser.showSaveDialog(this);
    if (res == javax.swing.JFileChooser.APPROVE_OPTION) {
        java.io.File file = chooser.getSelectedFile();
        try (java.io.FileOutputStream fos = new java.io.FileOutputStream(file)) {
            java.util.Properties p = buildConfigProps();
            p.store(fos, "Packager GUI configuration");
            output.append("Configuración guardada en: " + file.getAbsolutePath() + "\n");
        } catch (Exception ex) {
            output.append("Error al guardar configuración: " + ex.getMessage() + "\n");
        }
    }
}

// Diálogo para cargar .properties
    private void loadConfigDialog() {
    javax.swing.JFileChooser chooser = new javax.swing.JFileChooser();
    chooser.setDialogTitle("Cargar configuración");
    int res = chooser.showOpenDialog(this);
    if (res == javax.swing.JFileChooser.APPROVE_OPTION) {
        java.io.File file = chooser.getSelectedFile();
        try (java.io.FileInputStream fis = new java.io.FileInputStream(file)) {
            java.util.Properties p = new java.util.Properties();
            p.load(fis);
            applyConfigProps(p);
            output.append("Configuración cargada desde: " + file.getAbsolutePath() + "\n");
        } catch (Exception ex) {
            output.append("Error al cargar configuración: " + ex.getMessage() + "\n");
        }
    }
}

