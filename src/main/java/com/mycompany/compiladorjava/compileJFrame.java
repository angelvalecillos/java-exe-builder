    private void runJPackage(JPackageOptions.Type type) {
        output.append("== Ejecutando jpackage (" + type + ") ==\n");
        JPackageOptions opt = new JPackageOptions();
        opt.jpackageExe = tfJpackage.getText().trim();
        opt.type = type;
        opt.name = tfName.getText().trim();
        opt.inputDir = tfInput.getText().trim();
        opt.mainJar = tfMainJar.getText().trim();
        opt.mainClass = tfMainClass.getText().trim();
        opt.appVersion = tfVersion.getText().trim();
        opt.vendor = tfVendor.getText().trim();
        opt.destDir = tfDest.getText().trim();
        opt.iconPath = tfIcon.getText().trim();

        if (type == JPackageOptions.Type.EXE) {
            opt.winShortcut = cbWinShortcut.isSelected();
            opt.winMenu = cbWinMenu.isSelected();
            opt.winDirChooser = cbWinDirChooser.isSelected();
            opt.winPerUserInstall = cbWinPerUser.isSelected();
        }

        List<String> cmd = opt.toCommand();
        try {
            CommandRunner.run(cmd, output);
        } catch (Exception ex) {
            output.append("Error: " + ex.getMessage() + "\n");
            ex.printStackTrace();
        }
    }

    private void signFile(String filePath) {
        output.append("== Firmando: " + filePath + " ==\n");
        SignOptions so = new SignOptions();
        so.signtoolExe = tfSigntool.getText().trim();
        so.pfxPath = tfPfxPath.getText().trim();
        so.pfxPassword = new String(pfPfxPass.getPassword());
        so.timestampUrl = tfTimestamp.getText().trim();

        // Asegurar que no esté solo-lectura
        new File(filePath).setWritable(true);

        try {
            CommandRunner.run(so.signCommand(filePath), output);
        } catch (Exception ex) {
            output.append("Error: " + ex.getMessage() + "\n");
        }
    }
    
